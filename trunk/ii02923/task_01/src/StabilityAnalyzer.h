#pragma once

#include <string>

/**
 * @brief Модуль анализа устойчивости дискретных моделей.
 *
 * Для линейной модели первого порядка
 *     y_{t+1} = a * y_t + b * u_t
 * характеристическое уравнение имеет вид z - a = 0, то есть z = a.
 * По критерию устойчивости дискретной системы корень должен лежать
 * внутри единичной окружности Z-плоскости: |z| < 1.
 */
class StabilityAnalyzer {
public:
    /// Проверка условия |a| < 1 (строгая устойчивость).
    static bool isStableFirstOrder(double a);

    /// Текстовое заключение об устойчивости для печати в консоль.
    static std::string verdict(double a);
};
