#include "HarmonicODE.h"
#include <cmath>    // нужен для std::sin

// =====================================================================
// КОНСТРУКТОР
// Инициализируем только коэффициенты. Переменная y_harmonic уже
// инициализирована в .h файле значением 0.0.
// =====================================================================
HarmonicODE::HarmonicODE(double b_, double dt_)
    : amplitude_b(b_), time_step_dt(dt_)
{
    // Тело пустое: все данные проинициализированы выше.
}

// =====================================================================
// ADVANCE — один шаг метода Эйлера для гармонической модели.
// Формула: y(t+1) = y(t) + dt * b * sin(u(t))
// =====================================================================
double HarmonicODE::advance(double u)
{
    // Вычисляем производную: dy/dt = b * sin(u).
    // Используем наше уникальное имя amplitude_b вместо общего b.
    const double dy_dt = amplitude_b * std::sin(u);

    // Обновляем состояние по методу Эйлера.
    y_harmonic = y_harmonic + time_step_dt * dy_dt;

    // Возвращаем новое значение выхода.
    return y_harmonic;
}

// =====================================================================
// RESET — сброс модели в начальное состояние.
// =====================================================================
void HarmonicODE::reset()
{
    y_harmonic = 0.0;
}

// =====================================================================
// TITLE — название модели (выводится в консоль и в отчёт).
// =====================================================================
std::string HarmonicODE::title() const
{
    return "Model 3.5 (Harmonic Driving Force)";
}
