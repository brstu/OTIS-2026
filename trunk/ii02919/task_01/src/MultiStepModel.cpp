#include "MultiStepModel.h"
#include <cmath>
#include <sstream>

// ---------------------------------------------------------------------------
//  Конструктор: сохраняем коэффициенты, обнуляем состояние
// ---------------------------------------------------------------------------
MultiStepModel::MultiStepModel(double a_, double b1_, double b2_, double b3_)
    : a(a_), b1(b1_), b2(b2_), b3(b3_),
      y(0.0), u_prev1(0.0), u_prev2(0.0)
{
    // Тело пустое — всё сделано в списке инициализации выше.
}

// ---------------------------------------------------------------------------
//  advance — один шаг симуляции
//  y(t+1) = a*y(t) + b1*u(t) + b2*u(t-1) + b3*u(t-2)
// ---------------------------------------------------------------------------
double MultiStepModel::advance(double u)
{
    const double y_next = a * y + b1 * u + b2 * u_prev1 + b3 * u_prev2;

    // Сдвигаем историю входов: u_prev2 ← u_prev1, u_prev1 ← u
    u_prev2 = u_prev1;
    u_prev1 = u;
    y = y_next;

    return y;
}

// ---------------------------------------------------------------------------
//  reset — сброс состояния к начальному
// ---------------------------------------------------------------------------
void MultiStepModel::reset()
{
    y = 0.0;
    u_prev1 = 0.0;
    u_prev2 = 0.0;
}

// ---------------------------------------------------------------------------
//  title — название модели
// ---------------------------------------------------------------------------
std::string MultiStepModel::title() const
{
    return "Model 1.7 (Multi-Step Control History)";
}

// ---------------------------------------------------------------------------
//  isStableSystem — проверка устойчивости
//  Характеристическое уравнение: z - a = 0  →  z = a
//  Условие устойчивости: |a| < 1
// ---------------------------------------------------------------------------
bool MultiStepModel::isStableSystem() const
{
    return std::abs(a) < 1.0;
}

// ---------------------------------------------------------------------------
//  alertText — предупреждение при неустойчивости
// ---------------------------------------------------------------------------
std::string MultiStepModel::alertText() const
{
    const double abs_a = std::abs(a);
    if (abs_a < 1.0) return "";

    std::ostringstream oss;
    if (abs_a == 1.0)
    {
        oss << "[WARN] Model 1.7: |a| = 1 (" << a
            << "), система на границе устойчивости (незатухающие колебания).";
    }
    else
    {
        oss << "[WARN] Model 1.7: |a| = " << abs_a
            << " >= 1, система НЕУСТОЙЧИВА, y будет расходиться!";
    }
    return oss.str();
}
