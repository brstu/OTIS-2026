#include "MultiStepModel.h"
#include <cmath>    // для std::abs
#include <sstream>  // для формирования текста предупреждения

// =====================================================================
// КОНСТРУКТОР
// =====================================================================
MultiStepModel::MultiStepModel(double a_, double b1_, double b2_, double b3_)
    : coef_a(a_), coef_b1(b1_), coef_b2(b2_), coef_b3(b3_)
{
    // Состояния y_step, u_history_1, u_history_2 уже инициализированы
    // нулями в .h файле.
}

// =====================================================================
// ADVANCE — один шаг симуляции для многошаговой модели.
// Формула: y(t+1) = a*y(t) + b1*u(t) + b2*u(t-1) + b3*u(t-2)
// =====================================================================
double MultiStepModel::advance(double u)
{
    // Шаг 1: вычисляем новое значение выхода отдельной переменной.
    // Разбиваем формулу на строки — так повышается читаемость кода
    // и одновременно убирается дублирование с другими моделями.
    double new_value = coef_a * y_step;
    new_value += coef_b1 * u;
    new_value += coef_b2 * u_history_1;
    new_value += coef_b3 * u_history_2;

    // Шаг 2: сдвигаем историю входов:
    // старое u(t-1) становится u(t-2), текущее u — новым u(t-1).
    u_history_2 = u_history_1;
    u_history_1 = u;

    // Шаг 3: сохраняем новое значение выхода в состояние.
    y_step = new_value;

    return y_step;
}

// =====================================================================
// RESET — сброс состояния модели в начальное.
// =====================================================================
void MultiStepModel::reset()
{
    y_step = 0.0;
    u_history_1 = 0.0;
    u_history_2 = 0.0;
}

// =====================================================================
// TITLE — название модели.
// =====================================================================
std::string MultiStepModel::title() const
{
    return "Model 1.7 (Multi-Step Control History)";
}

// =====================================================================
// ISSTABLESYSTEM — проверка устойчивости.
// Характеристическое уравнение: z - a = 0  =>  корень z = a.
// Система устойчива, если |a| < 1.
// =====================================================================
bool MultiStepModel::isStableSystem() const
{
    return std::abs(coef_a) < 1.0;
}

// =====================================================================
// ALERTTEXT — формирует текст предупреждения, если система неустойчива.
// =====================================================================
std::string MultiStepModel::alertText() const
{
    if (isStableSystem()) {
        return "";
    }

    std::ostringstream oss;
    oss << "Linear model is UNSTABLE: |a| >= 1 (a = " << coef_a << "). "
        << "The output will diverge.";
    return oss.str();
}
