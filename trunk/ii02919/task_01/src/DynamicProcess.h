#pragma once

#include <string>

// =====================================================================
// DynamicProcess — абстрактный базовый класс для всех динамических моделей.
// Определяет общий интерфейс: шаг симуляции, сброс, название, устойчивость.
// =====================================================================
class DynamicProcess
{
public:
    // Виртуальный деструктор: нужен, чтобы при удалении через указатель
    // базового класса корректно вызывались деструкторы наследников.
    virtual ~DynamicProcess() = default;

    // Чисто виртуальный метод (шаг симуляции).
    // На входе — управляющее воздействие u(tau), на выходе — новое y(tau+1).
    virtual double advance(double u) = 0;

    // Сброс состояния модели в начальное (y=0, истории обнуляются).
    virtual void reset() = 0;

    // Человекочитаемое название модели (например, "Model 3.5").
    virtual std::string title() const = 0;

    // Проверка устойчивости. По умолчанию для нелинейных моделей — true.
    // Линейные модели переопределяют этот метод.
    virtual bool isStableSystem() const
    {
        return true;
    }

    // Текст предупреждения о неустойчивости (пустой, если всё ок).
    virtual std::string alertText() const
    {
        return "";
    }
};
