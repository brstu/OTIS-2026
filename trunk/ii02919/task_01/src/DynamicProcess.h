#pragma once

#include <string>

// ============================================================================
//  DynamicProcess — абстрактный базовый класс динамических процессов
//  Определяет общий интерфейс: расчёт шага, сброс состояния,
//  название, проверка устойчивости.
// ============================================================================
class DynamicProcess
{
public:
    virtual ~DynamicProcess() = default;

    // Один шаг симуляции: на входе управляющее воздействие u,
    // возвращает новое значение y.
    virtual double advance(double u) = 0;

    // Возврат процесса в начальное состояние.
    virtual void reset() = 0;

    // Человекочитаемое название процесса (для вывода).
    virtual std::string title() const = 0;

    // Проверка устойчивости. Для линейных моделей — через
    // характеристическое уравнение; для нелинейных — всегда true.
    virtual bool isStableSystem() const
    {
        return true;
    }

    // Текст предупреждения о неустойчивости (пусто, если всё ок).
    virtual std::string alertText() const
    {
        return "";
    }
};

