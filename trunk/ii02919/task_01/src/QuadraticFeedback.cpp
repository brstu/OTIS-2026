#include "QuadraticFeedback.h"
#include <cmath>

// ---------------------------------------------------------------------------
//  Конструктор
// ---------------------------------------------------------------------------
QuadraticFeedback::QuadraticFeedback(double a_, double b_, double c_, double d_)
    : a(a_), b(b_), c(c_), d(d_),
      y(0.0), y_prev(0.0), u_prev(0.0)
{
}

// ---------------------------------------------------------------------------
//  advance — один шаг симуляции
//  y(t+1) = a*y(t) - b*y(t-1)^2 + c*u(t) + d*sin(u(t-1))
// ---------------------------------------------------------------------------
double QuadraticFeedback::advance(double u)
{
    // Сначала считаем новое значение, используя ТЕКУЩИЕ y и y_prev
    const double y_next = a * y
                        - b * y_prev * y_prev
                        + c * u
                        + d * std::sin(u_prev);

    // Сдвигаем историю: y_prev ← y (старое), y ← y_next
    y_prev = y;
    y = y_next;

    // Запоминаем вход для следующего шага
    u_prev = u;

    return y;
}

// ---------------------------------------------------------------------------
//  reset
// ---------------------------------------------------------------------------
void QuadraticFeedback::reset()
{
    y = 0.0;
    y_prev = 0.0;
    u_prev = 0.0;
}

// ---------------------------------------------------------------------------
//  title
// ---------------------------------------------------------------------------
std::string QuadraticFeedback::title() const
{
    return "Model 2.1 (Quadratic Feedback and Harmonic Control)";
}
