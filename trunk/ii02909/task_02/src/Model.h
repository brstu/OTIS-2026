#include <string>

// Абстрактный класс, определяющий поведение любой модели
class Model {
public:
    virtual ~Model() = default;

    // Выполнить один шаг симуляции (вход u -> выход y)
    virtual double next(double u) = 0;

    // Вернуть модель в начальное состояние
    virtual void reset() = 0;

    // Получить строковое имя модели
    virtual std::string name() const = 0;

    // --- Анализ устойчивости (переопределяется в наследниках) ---
    // По умолчанию считаем модель устойчивой (для нелинейных моделей)
    virtual bool isStable() const { return true; }

    // Вернуть текст предупреждения (по умолчанию пусто)
    virtual std::string stabilityWarning() const { return ""; }
};